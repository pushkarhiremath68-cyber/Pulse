export async function fetchCategoryTracks(catId, limit = 30) {
  const found = CATALOG_CATEGORIES.find(c => c.id === catId);
  if (found && found.tracks) {
    return found.tracks.map((t, idx) => ({
      id: `${catId}-${idx}`,
      title: t.title,
      artist: t.artist,
      coverUrl: t.cover,
      streamUrl: t.stream,
      duration: t.duration || 220,
      source: found.title
    }));
  }
  return [];
}

const catalogService = {
  CATALOG_CATEGORIES,
  fetchCategoryTracks
};

if (typeof window !== 'undefined') {
  window.catalogService = catalogService;
}

export default catalogService;
