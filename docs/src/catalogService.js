export async function fetchCategoryTracks(catId, limit = 30) {
  const found = CATALOG_CATEGORIES.find(c => c.id === catId);
  if (found && found.tracks) {
    return found.tracks.map((t, idx) => ({
      id: `${catId}-${idx}`,
      title: t.title,
      artist: t.artist,
      coverUrl: t.cover,
      streamUrl: t.stream,
      duration: t.duration || 210,
      source: found.title
    }));
  }
  return [];
}

