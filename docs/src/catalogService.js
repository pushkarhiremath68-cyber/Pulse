export async function fetchCategoryTracks(catId, limit = 40) {
  const found = CATALOG_CATEGORIES.find(c => c.id === catId);
  if (found && found.tracks && found.tracks.length > 0) {
    return found.tracks.map((t, idx) => ({
      id: `${catId}-${idx}`,
      title: t.title,
      artist: t.artist,
      coverUrl: t.cover,
      streamUrl: t.stream,
      duration: t.duration || 210,
      source: `${found.title} (Full Song)`
    }));
  }
  if (window.musicService && typeof window.musicService.searchTracks === 'function') {
    return await window.musicService.searchTracks(catId, limit);
  }
  return [];
}

const catalogService = {
  CATALOG_CATEGORIES,
  fetchCategoryTracks
};

if (typeof window !== 'undefined') {
  window.catalogService = catalogService;
}

export default catalogService;
